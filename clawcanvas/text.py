CHAR_W = 5
CHAR_H = 7


class TextRenderer:
    """Renders text onto a canvas pixel grid using a built-in 5×7 monospace font."""

    def __init__(self, scale: int = 1, color: Color | None = None) -> None:
        self.scale = scale
        self.color = color or Color(0, 0, 0)

    @staticmethod
    def char_width() -> int:
        return CHAR_W

    @staticmethod
    def char_height() -> int:
        return CHAR_H

    def measure(self, text: str) -> tuple[int, int]:
        """Return (width, height) in pixels for the given text (single line)."""
        if not text:
            return (0, 0)
        lines = text.split("\n")
        w = max(len(line) for line in lines) * (CHAR_W + 1) * self.scale
        h = len(lines) * (CHAR_H + 1) * self.scale
        return (w, h)

    def wrap_text(self, text: str, max_width: int) -> list[str]:
        """Word-wrap text to fit within max_width pixels."""
        max_chars = max(1, max_width // ((CHAR_W + 1) * self.scale))
        words = text.split()
        lines: list[str] = []
        current = ""
        for word in words:
            test = f"{current} {word}".strip() if current else word
            if len(test) <= max_chars:
                current = test
            else:
                if current:
                    lines.append(current)
                # Handle words longer than max_chars
                while len(word) > max_chars:
                    lines.append(word[:max_chars])
                    word = word[max_chars:]
                current = word
        if current:
            lines.append(current)
        return lines or [""]

    def render(
        self,
        grid: list[list[Color]],
        text: str,
        x: int,
        y: int,
        canvas_w: int,
        canvas_h: int,
        align: str = "left",
    ) -> None:
        """Render text onto grid at position (x, y)."""
        lines = text.split("\n")
        line_h = (CHAR_H + 1) * self.scale

        for li, line in enumerate(lines):
            ly = y + li * line_h
            # Compute x offset for alignment
            line_w = len(line) * (CHAR_W + 1) * self.scale
            if align == "center":
                lx = x - line_w // 2
            elif align == "right":
                lx = x - line_w
            else:
                lx = x

            for ci, ch in enumerate(line):
                glyph = _FONT.get(ch if ch in _FONT else ch.upper(), _FONT.get("?", _FONT[" "]))
                cx = lx + ci * (CHAR_W + 1) * self.scale
                for row in range(CHAR_H):
                    bits = glyph[row] if row < len(glyph) else 0
                    for col in range(CHAR_W):
                        if bits & (1 << (4 - col)):
                            for sy in range(self.scale):
                                for sx in range(self.scale):
                                    px = cx + col * self.scale + sx
                                    py = ly + row * self.scale + sy
                                    if 0 <= px < canvas_w and 0 <= py < canvas_h:
                                        grid[py][px] = self.color
